DROP DATABASE IF EXISTS gym_db;
CREATE DATABASE gym_db CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE gym_db;

-- ---------------------------------------------------------------------
-- Member Record (Kazuya Niki)
-- ---------------------------------------------------------------------
CREATE TABLE member (
    member_id         INT AUTO_INCREMENT PRIMARY KEY,
    last_name         VARCHAR(50)  NOT NULL,
    first_name        VARCHAR(50)  NOT NULL,
    birthdate         DATE         NOT NULL,
    sex               ENUM('Male', 'Female') NOT NULL,
    contact_number    VARCHAR(20),
    email             VARCHAR(100),
    membership_type   ENUM('Monthly', 'Quarterly', 'Annual') NOT NULL,
    membership_start  DATE         NOT NULL,
    membership_end    DATE         NOT NULL,
    status            ENUM('Active', 'Expired') NOT NULL DEFAULT 'Active',
    CONSTRAINT chk_member_dates CHECK (membership_end > membership_start)
);

-- ---------------------------------------------------------------------
-- Trainer Record (Jan Carlo Avelino)
-- ---------------------------------------------------------------------
CREATE TABLE trainer (
    trainer_id        INT AUTO_INCREMENT PRIMARY KEY,
    last_name         VARCHAR(50)  NOT NULL,
    first_name        VARCHAR(50)  NOT NULL,
    contact_number    VARCHAR(20),
    email             VARCHAR(100),
    specialization    VARCHAR(30)  NOT NULL,   -- martial arts discipline
    hire_date         DATE         NOT NULL,
    status            ENUM('Active', 'Inactive') NOT NULL DEFAULT 'Active'
);

-- ---------------------------------------------------------------------
-- Class Record (Charlotte Mae Ojeda)
-- One row per weekly class (discipline, level, day and time).
-- A trainer cannot be deleted while a class references them (RESTRICT).
-- ---------------------------------------------------------------------
CREATE TABLE gym_class (
    class_code        VARCHAR(10)  PRIMARY KEY,
    class_name        VARCHAR(60)  NOT NULL,
    description       VARCHAR(255),
    trainer_id        INT          NOT NULL,
    day_of_week       ENUM('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday') NOT NULL,
    start_time        TIME         NOT NULL,
    end_time          TIME         NOT NULL,
    max_capacity      INT          NOT NULL,
    status            ENUM('Active', 'Inactive') NOT NULL DEFAULT 'Active',
    CONSTRAINT chk_class_capacity CHECK (max_capacity > 0),
    CONSTRAINT fk_class_trainer FOREIGN KEY (trainer_id)
        REFERENCES trainer (trainer_id) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- ---------------------------------------------------------------------
-- Class Session Record
-- No two sessions of the same class on one date (unique key).
-- ---------------------------------------------------------------------
CREATE TABLE class_session (
    session_id        INT AUTO_INCREMENT PRIMARY KEY,
    class_code        VARCHAR(10)  NOT NULL,
    session_date      DATE         NOT NULL,
    status            ENUM('Held', 'Cancelled') NOT NULL DEFAULT 'Held',
    CONSTRAINT uq_session_class_date UNIQUE (class_code, session_date),
    CONSTRAINT fk_session_class FOREIGN KEY (class_code)
        REFERENCES gym_class (class_code) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- ---------------------------------------------------------------------
-- Class Attendance Record (Matthew Mari Manzano)
-- ---------------------------------------------------------------------
CREATE TABLE class_attendance (
    attendance_id     INT AUTO_INCREMENT PRIMARY KEY,
    member_id         INT          NOT NULL,
    session_id        INT          NOT NULL,
    time_in           TIME         NOT NULL,
    CONSTRAINT fk_attendance_member FOREIGN KEY (member_id)
        REFERENCES member (member_id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_attendance_session FOREIGN KEY (session_id)
        REFERENCES class_session (session_id) ON DELETE RESTRICT ON UPDATE CASCADE
);

